def default_image_for(name, category):
    if (name, category) in LOCAL_MENU_IMAGES:
        return LOCAL_MENU_IMAGES[(name, category)]

    for category_prefix, image_url in DEFAULT_CATEGORY_IMAGES:
        if category.startswith(category_prefix):
            return image_url

    return "https://images.unsplash.com/photo-1504674900247-0877df9cc836?auto=format&fit=crop&w=640&q=80"


def item(name, price, category, description="", image_url=""):
    return {
        "name": name,
        "description": description,
        "price": float(price),
        "category": category,
        "image_url": image_url or default_image_for(name, category),
        "is_available": True,
    }


